import sys, os
sys.path.insert(0, ".")
import excel_tool as et

et.enable_dpi_awareness()
app = et.App()
app.update()
app.load_rule_file("示例规则_村表补总表_全工作表.json")
app.update()
print("目标已选:", len(app.dst_selected_sheets()), "个工作表")
print("源表:", len(app.sources))
print("对应:", [(app.sources[p["src"]].sheet, p["target"]) for p in app.pairs])
print("匹配键:", app.key_pairs)
print("映射:", [(m["src_name"], m["dst_name"]) for m in app.mappings])
print("模式:", app.var_mode.get())
plans, warns = app.make_plans()
print("计划:", len(plans), "警告:", warns)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "测试输出", "规则加载_补全结果.xlsx")
os.makedirs(os.path.join(os.path.dirname(os.path.abspath(__file__)), "测试输出"), exist_ok=True)
et.execute_fill_multi(app.var_dst_path.get(), plans, out)
print("结果:", os.path.exists(out))
app.after(200, app.destroy)
app.mainloop()
print("规则流程测试通过")
